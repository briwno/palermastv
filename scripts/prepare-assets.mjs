import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { build } from 'esbuild';
import { renderShell } from './lib/render-shell.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const outputDirectory = path.join(root, 'src/generated');
const assets = {};

// Bundle in memory: browser source stays readable and private resources continue
// through the authenticated HTTP handler instead of Next's public directory.
const result = await build({
  absWorkingDir: root,
  entryPoints: {
    main: 'src/client/main.js',
    styles: 'src/client/styles/main.css',
    login: 'src/client/auth/login.js',
    'login-styles': 'src/client/auth/login.css',
  },
  outdir: 'assets',
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2022'],
  write: false,
  minify: false,
});
for (const file of result.outputFiles) {
  const name = path.basename(file.path);
  const isCSS = name.endsWith('.css');
  assets[`assets/${name === 'styles.css' ? 'main.css' : name}`] = {
    type: `${isCSS ? 'text/css' : 'text/javascript'}; charset=utf-8`,
    body: file.text,
  };
}
for (const [name, source, type] of [
  ['login.html', 'src/client/auth/login.html', 'text/html; charset=utf-8'],
  [
    'sw.js',
    'src/client/pwa/service-worker.js',
    'text/javascript; charset=utf-8',
  ],
]) {
  assets[name] = {
    type,
    body: await readFile(path.join(root, source), 'utf8'),
  };
}

await mkdir(outputDirectory, { recursive: true });
assets['index.html'] = {
  type: 'text/html; charset=utf-8',
  body: await renderShell(),
};
await writeFile(
  path.join(outputDirectory, 'site-assets.js'),
  '// Generated by scripts/prepare-assets.mjs. Do not edit.\n' +
    `export const assets = ${JSON.stringify(assets)};\n`,
);
